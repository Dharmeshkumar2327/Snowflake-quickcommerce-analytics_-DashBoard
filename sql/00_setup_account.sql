/* =============================================================================
   00_setup_account.sql
   DashCart Quick-Commerce Analytics on Snowflake
   -----------------------------------------------------------------------------
   Creates: roles (RBAC hierarchy), right-sized warehouses, a resource monitor,
   the DASHCART database and its medallion-style schemas.
   Run as: ACCOUNTADMIN (once). Everything after this runs as DASHCART_ENGINEER.
============================================================================= */

USE ROLE ACCOUNTADMIN;

-- ---------------------------------------------------------------------------
-- 1. Roles  (functional roles -> rolled up to SYSADMIN, least privilege)
--
--    DASHCART_ADMIN          owns all objects
--      └── DASHCART_ENGINEER builds pipelines, tasks, dynamic tables
--            └── DASHCART_ANALYST     reads CORE + MARTS, PII masked
--                  └── DASHCART_CITY_MANAGER  MARTS only, row-filtered to own city
-- ---------------------------------------------------------------------------
CREATE ROLE IF NOT EXISTS DASHCART_ADMIN;
CREATE ROLE IF NOT EXISTS DASHCART_ENGINEER;
CREATE ROLE IF NOT EXISTS DASHCART_ANALYST;
CREATE ROLE IF NOT EXISTS DASHCART_CITY_MANAGER;

GRANT ROLE DASHCART_CITY_MANAGER TO ROLE DASHCART_ANALYST;
GRANT ROLE DASHCART_ANALYST      TO ROLE DASHCART_ENGINEER;
GRANT ROLE DASHCART_ENGINEER     TO ROLE DASHCART_ADMIN;
GRANT ROLE DASHCART_ADMIN        TO ROLE SYSADMIN;

-- Per-city manager roles (row access policy in 07 maps each to one city)
CREATE ROLE IF NOT EXISTS DASHCART_CITY_MANAGER_BLR;
CREATE ROLE IF NOT EXISTS DASHCART_CITY_MANAGER_BOM;
CREATE ROLE IF NOT EXISTS DASHCART_CITY_MANAGER_DEL;
GRANT ROLE DASHCART_CITY_MANAGER     TO ROLE DASHCART_CITY_MANAGER_BLR;
GRANT ROLE DASHCART_CITY_MANAGER     TO ROLE DASHCART_CITY_MANAGER_BOM;
GRANT ROLE DASHCART_CITY_MANAGER     TO ROLE DASHCART_CITY_MANAGER_DEL;
GRANT ROLE DASHCART_CITY_MANAGER_BLR TO ROLE DASHCART_ADMIN;   -- so the admin can test as each city
GRANT ROLE DASHCART_CITY_MANAGER_BOM TO ROLE DASHCART_ADMIN;
GRANT ROLE DASHCART_CITY_MANAGER_DEL TO ROLE DASHCART_ADMIN;

-- Give yourself the admin role (replace with your user name)
SET my_user = CURRENT_USER();
GRANT ROLE DASHCART_ADMIN TO USER IDENTIFIER($my_user);

-- Account-level privileges needed by the engineering role
GRANT EXECUTE TASK, EXECUTE MANAGED TASK ON ACCOUNT TO ROLE DASHCART_ENGINEER;
GRANT EXECUTE ALERT                      ON ACCOUNT TO ROLE DASHCART_ENGINEER;
GRANT CREATE DATABASE                    ON ACCOUNT TO ROLE DASHCART_ADMIN;
GRANT APPLY MASKING POLICY, APPLY ROW ACCESS POLICY, APPLY TAG ON ACCOUNT TO ROLE DASHCART_ADMIN;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER          TO ROLE DASHCART_ANALYST;   -- Cortex LLM functions
GRANT DATABASE ROLE SNOWFLAKE.DATA_METRIC_USER     TO ROLE DASHCART_ENGINEER;  -- Data Metric Functions
GRANT EXECUTE DATA METRIC FUNCTION ON ACCOUNT      TO ROLE DASHCART_ENGINEER;
GRANT APPLICATION ROLE SNOWFLAKE.DATA_QUALITY_MONITORING_VIEWER TO ROLE DASHCART_ENGINEER;  -- DMF results
GRANT IMPORTED PRIVILEGES ON DATABASE SNOWFLAKE    TO ROLE DASHCART_ADMIN;     -- ACCOUNT_USAGE for cost views

-- ---------------------------------------------------------------------------
-- 2. Warehouses  (workload isolation: load / transform / BI / ML)
-- ---------------------------------------------------------------------------
CREATE WAREHOUSE IF NOT EXISTS DASHCART_LOAD_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  COMMENT = 'COPY INTO / Snowpipe backfills';

CREATE WAREHOUSE IF NOT EXISTS DASHCART_TRANSFORM_WH
  WAREHOUSE_SIZE = 'SMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  COMMENT = 'Tasks, MERGE, dynamic table refreshes';

CREATE WAREHOUSE IF NOT EXISTS DASHCART_BI_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  MIN_CLUSTER_COUNT = 1 MAX_CLUSTER_COUNT = 3 SCALING_POLICY = 'STANDARD'   -- multi-cluster (Enterprise+)
  COMMENT = 'Dashboards & ad-hoc analysis; scales out for concurrency';

CREATE WAREHOUSE IF NOT EXISTS DASHCART_ML_WH
  WAREHOUSE_SIZE = 'MEDIUM' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  COMMENT = 'Cortex ML training, Snowpark procedures';

-- ---------------------------------------------------------------------------
-- 3. Cost guardrail: resource monitor (monthly credit quota)
-- ---------------------------------------------------------------------------
CREATE OR REPLACE RESOURCE MONITOR DASHCART_MONTHLY_RM
  WITH CREDIT_QUOTA = 50
       FREQUENCY = MONTHLY
       START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 75  PERCENT DO NOTIFY
           ON 90  PERCENT DO SUSPEND
           ON 100 PERCENT DO SUSPEND_IMMEDIATE;

ALTER WAREHOUSE DASHCART_LOAD_WH      SET RESOURCE_MONITOR = DASHCART_MONTHLY_RM;
ALTER WAREHOUSE DASHCART_TRANSFORM_WH SET RESOURCE_MONITOR = DASHCART_MONTHLY_RM;
ALTER WAREHOUSE DASHCART_BI_WH        SET RESOURCE_MONITOR = DASHCART_MONTHLY_RM;
ALTER WAREHOUSE DASHCART_ML_WH        SET RESOURCE_MONITOR = DASHCART_MONTHLY_RM;

-- Kill runaway queries
ALTER WAREHOUSE DASHCART_BI_WH SET STATEMENT_TIMEOUT_IN_SECONDS = 600;

GRANT USAGE, OPERATE ON WAREHOUSE DASHCART_LOAD_WH      TO ROLE DASHCART_ENGINEER;
GRANT USAGE, OPERATE ON WAREHOUSE DASHCART_TRANSFORM_WH TO ROLE DASHCART_ENGINEER;
GRANT USAGE, OPERATE ON WAREHOUSE DASHCART_ML_WH        TO ROLE DASHCART_ENGINEER;
GRANT USAGE          ON WAREHOUSE DASHCART_ML_WH        TO ROLE DASHCART_ANALYST;
GRANT USAGE          ON WAREHOUSE DASHCART_BI_WH        TO ROLE DASHCART_CITY_MANAGER;

-- ---------------------------------------------------------------------------
-- 4. Database & schemas (medallion layout)
--    RAW        bronze  - files landed as-is (+ load metadata)
--    STAGING    silver  - typed, de-duplicated, JSON flattened
--    CORE       gold    - conformed star schema (SCD2 dims, facts)
--    MARTS      platinum- dynamic tables for BI
--    ML         Cortex ML models, predictions, LLM enrichments
--    GOVERNANCE tags, masking & row access policies
--    UTIL       DQ results, procedures, alerts, logging
-- ---------------------------------------------------------------------------
USE ROLE DASHCART_ADMIN;

CREATE DATABASE IF NOT EXISTS DASHCART
  DATA_RETENTION_TIME_IN_DAYS = 7         -- Time Travel window (Enterprise allows up to 90)
  COMMENT = 'DashCart quick-commerce analytics';

CREATE SCHEMA IF NOT EXISTS DASHCART.RAW        WITH MANAGED ACCESS;
CREATE SCHEMA IF NOT EXISTS DASHCART.STAGING    WITH MANAGED ACCESS;
CREATE SCHEMA IF NOT EXISTS DASHCART.CORE       WITH MANAGED ACCESS;
CREATE SCHEMA IF NOT EXISTS DASHCART.MARTS      WITH MANAGED ACCESS;
CREATE SCHEMA IF NOT EXISTS DASHCART.ML         WITH MANAGED ACCESS;
CREATE SCHEMA IF NOT EXISTS DASHCART.GOVERNANCE WITH MANAGED ACCESS;
CREATE SCHEMA IF NOT EXISTS DASHCART.UTIL       WITH MANAGED ACCESS;

-- Engineer builds everything except governance policies
GRANT USAGE ON DATABASE DASHCART TO ROLE DASHCART_CITY_MANAGER;
GRANT USAGE, CREATE TABLE, CREATE VIEW, CREATE STAGE, CREATE FILE FORMAT, CREATE PIPE,
      CREATE STREAM, CREATE TASK, CREATE DYNAMIC TABLE, CREATE PROCEDURE, CREATE FUNCTION,
      CREATE SEQUENCE, CREATE ALERT, CREATE STREAMLIT, CREATE DATA METRIC FUNCTION
  ON ALL SCHEMAS IN DATABASE DASHCART TO ROLE DASHCART_ENGINEER;
GRANT CREATE SNOWFLAKE.ML.FORECAST          ON SCHEMA DASHCART.ML TO ROLE DASHCART_ENGINEER;
GRANT CREATE SNOWFLAKE.ML.ANOMALY_DETECTION ON SCHEMA DASHCART.ML TO ROLE DASHCART_ENGINEER;
GRANT CREATE SNOWFLAKE.ML.CLASSIFICATION    ON SCHEMA DASHCART.ML TO ROLE DASHCART_ENGINEER;

-- Analysts: read CORE / MARTS / ML (current + future objects)
GRANT USAGE ON SCHEMA DASHCART.CORE    TO ROLE DASHCART_ANALYST;
GRANT USAGE ON SCHEMA DASHCART.STAGING TO ROLE DASHCART_ANALYST;   -- clickstream analysis (Q4)
GRANT USAGE ON SCHEMA DASHCART.ML    TO ROLE DASHCART_ANALYST;
GRANT USAGE ON SCHEMA DASHCART.MARTS TO ROLE DASHCART_CITY_MANAGER;
GRANT SELECT ON FUTURE TABLES         IN SCHEMA DASHCART.CORE  TO ROLE DASHCART_ANALYST;
GRANT SELECT ON FUTURE VIEWS          IN SCHEMA DASHCART.CORE  TO ROLE DASHCART_ANALYST;
GRANT SELECT ON FUTURE TABLES         IN SCHEMA DASHCART.ML    TO ROLE DASHCART_ANALYST;
GRANT SELECT ON FUTURE VIEWS          IN SCHEMA DASHCART.ML    TO ROLE DASHCART_ANALYST;
GRANT SELECT ON FUTURE VIEWS          IN SCHEMA DASHCART.STAGING TO ROLE DASHCART_ANALYST;
GRANT SELECT ON FUTURE DYNAMIC TABLES IN SCHEMA DASHCART.MARTS TO ROLE DASHCART_CITY_MANAGER;
GRANT SELECT ON FUTURE VIEWS          IN SCHEMA DASHCART.MARTS TO ROLE DASHCART_CITY_MANAGER;

-- Landing stage (created here so data can be uploaded before 01 runs)
CREATE STAGE IF NOT EXISTS DASHCART.RAW.LANDING
  DIRECTORY = (ENABLE = TRUE)
  ENCRYPTION = (TYPE = 'SNOWFLAKE_SSE')
  COMMENT = 'Landing zone for DashCart extracts';
GRANT READ, WRITE ON STAGE DASHCART.RAW.LANDING TO ROLE DASHCART_ENGINEER;

-- Sanity check
SHOW SCHEMAS IN DATABASE DASHCART;
